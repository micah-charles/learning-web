/**
 * Study Book Core — shared pure functions for markdown rendering & TOC extraction.
 * No DOM dependencies — safe to import in both browser (via Vite) and Node.js build scripts.
 */

import { marked } from "marked";

// ── Marked configuration ───────────────────────────────────────────────────

marked.use({
  gfm: true,
  breaks: false,
  renderer: (() => {
    const renderer = new marked.Renderer();
    renderer.heading = function ({ text, depth }) {
      const anchor = text
        .toLowerCase()
        .replace(/[^\w\s-]/g, "")
        .replace(/\s+/g, "-")
        .replace(/-+/g, "-")
        .replace(/^-|-$/g, "");
      return `<h${depth} id="${anchor}">${text}</h${depth}>\n`;
    };
    return renderer;
  })(),
});

export { marked };

export function makeStudyBookAnchor(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

// ── Allowed HTML tags/attrs (for DOMPurify in the browser) ────────────

export const ALLOWED_TAGS = [
  "h1", "h2", "h3", "h4", "h5", "h6",
  "p", "ul", "ol", "li",
  "table", "thead", "tbody", "tr", "th", "td",
  "blockquote", "pre", "code",
  "strong", "em", "a", "hr", "br",
  "span", "div", "mark",
];

export const ALLOWED_ATTR = ["href", "id", "class", "target", "rel"];

// ── Table of contents ──────────────────────────────────────────────────

/**
 * Extracts h1/h2/h3 headings from raw markdown and returns a TOC array.
 * Each entry: { level: 1|2|3, text: string, anchor: string }
 * The anchor matches the id generated by the custom renderer above.
 */
export function extractTOC(rawMarkdown) {
  const toc = [];
  const re = /^(#{1,3})\s+(.+)$/gm;
  let match;
  while ((match = re.exec(rawMarkdown)) !== null) {
    const level = match[1].length;
    const text = match[2].trim();
    const anchor = makeStudyBookAnchor(text);
    toc.push({ level, text, anchor });
  }
  return toc;
}

export function hasStudyBookAnchor(rawMarkdown, requestedAnchor) {
  if (!requestedAnchor) return true;
  const re = /^(#{1,6})\s+(.+)$/gm;
  let match;
  while ((match = re.exec(rawMarkdown)) !== null) {
    if (makeStudyBookAnchor(match[2].trim()) === requestedAnchor) {
      return true;
    }
  }
  return false;
}

// ── Search / highlight ─────────────────────────────────────────────────

/**
 * Wraps every occurrence of `query` in the rendered HTML with
 * <mark class="sb-highlight">…</mark>.
 * Returns { html: string, count: number }.
 * Returns the original html unchanged if query is too short.
 */
export function highlightMatches(html, query) {
  if (!query || query.trim().length < 2) return { html, count: 0 };
  const escaped = query.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp(`(${escaped})`, "gi");
  let count = 0;
  const highlighted = html.replace(re, (m) => {
    count++;
    return `<mark class="sb-highlight">${m}</mark>`;
  });
  return { html: highlighted, count };
}

// ── Dataset helpers ────────────────────────────────────────────────────

/**
 * Returns true if the dataset has at least one markdown file registered.
 */
export function datasetHasStudyBook(dataset) {
  return !!(dataset?.contentMdPath || dataset?.extraMdFiles?.length);
}

/**
 * Returns an ordered list of { title, path } for all MD files in a dataset.
 * The primary contentMdPath is listed first with the title "Notes".
 */
export function getStudyBookFiles(dataset) {
  const files = [];
  if (dataset?.contentMdPath) {
    files.push({ title: "Notes", path: dataset.contentMdPath });
  }
  for (const extra of dataset?.extraMdFiles ?? []) {
    if (extra?.path) files.push({ title: extra.title || "More notes", path: extra.path });
  }
  return files;
}
